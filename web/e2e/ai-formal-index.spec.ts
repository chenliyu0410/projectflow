import { expect, test } from '@playwright/test';
import { chooseCategory, openAdvanced, openSources } from './copilot';

test.use(process.platform === 'win32' ? { channel: 'msedge' } : {});

for (const width of [1280, 375]) test(`isolated operational documents and attachments ${width}`, async ({ page }, info) => {
  test.setTimeout(60000);
  expect(await (await page.request.get('/api/health/acceptance')).json()).toEqual({ acceptance: true });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(String(error)));
  await page.setViewportSize({ width, height: 900 });
  await page.goto('/');
  await page.getByLabel('帳號').fill('yu');
  await page.getByLabel('密碼').fill('demo-yu');
  await page.getByRole('button', { name: '登入', exact: true }).click();
  await expect(page.getByRole('heading', { name: '所有專案總覽' })).toBeVisible();
  expect((await (await page.request.get('/api/ai/status')).json()).formal_available).toBe(true);
  const created = await page.request.post('/api/projects', { data: { title: `隔離索引展示 ${width} ${Date.now()}` } });
  expect(created.status()).toBe(201);
  const project = await created.json();
  const nodeResponse = await page.request.post(`/api/projects/${project.id}/nodes`, { data: { title: '新人設備資料（虛構）', kind: 'task' } });
  expect(nodeResponse.status()).toBe(201);
  const node = await nodeResponse.json();
  const docResponse = await page.request.post(`/api/projects/${project.id}/documents?filename=${encodeURIComponent('新人報到指南.txt')}`, { data: Buffer.from('全部虛構。新人報到請到三樓人資部，請攜帶識別證。'), headers: { 'Content-Type': 'application/octet-stream' } });
  expect(docResponse.status()).toBe(201);
  const doc = await docResponse.json();
  const attachment = await page.request.post(`/api/nodes/${node.id}/attachments?filename=${encodeURIComponent('設備申請流程.txt')}`, { data: Buffer.from('全部虛構。設備申請流程：由人資登記新人筆電需求，再由資訊同仁準備。'), headers: { 'Content-Type': 'application/octet-stream' } });
  expect(attachment.status()).toBe(201);
  await page.getByRole('button', { name: '切換 AI 副手' }).click();
  const panel = page.getByLabel('AI 專案副手', { exact: true });
  await chooseCategory(panel, '正式文件');
  await openAdvanced(panel);
  await expect(panel).toContainText('待更新');
  await panel.getByRole('button', { name: '更新文件索引' }).click();
  await expect(panel.getByRole('button', { name: '更新文件索引' })).toBeEnabled();
  await panel.getByLabel('詢問 AI').fill('新人報到');
  await panel.getByRole('button', { name: '預覽提供給模型的資料' }).click();
  await expect(panel.getByLabel('模型資料預覽', { exact: true })).toContainText('資料等級：機密');
  await panel.getByRole('button', { name: '送出 AI 問題' }).click();
  await expect(panel.locator('.ai-sources')).toContainText('新人報到指南.txt');
  await openSources(panel);
  await panel.locator('.ai-sources summary').filter({ hasText: '新人報到指南.txt' }).click();
  await panel.getByRole('button', { name: '開啟索引段落：新人報到指南.txt／1' }).click();
  await expect(panel.getByLabel('引用原文')).toContainText('三樓');
  await panel.getByRole('button', { name: '關閉原文' }).click();
  const updated = await page.request.post(`/api/documents/${doc.document_id}/text`, { data: { expected_version: 1, content: '全部虛構。新人報到改到五樓，請攜帶識別證。' } });
  expect(updated.status()).toBe(201);
  const beforeRefresh = await page.request.post('/api/ai/ask', { data: { dataset: 'formal-v1', question: '新人報到', project_id: project.id } });
  expect((await beforeRefresh.json()).sources.some((source: { title: string; version: number }) => source.title === '新人報到指南.txt' && source.version === 1)).toBe(false);
  await openAdvanced(panel);
  await panel.getByRole('button', { name: '更新文件索引' }).click();
  await expect(panel.getByRole('button', { name: '更新文件索引' })).toBeEnabled();
  await panel.getByLabel('詢問 AI').fill('新人報到');
  await panel.getByRole('button', { name: '送出 AI 問題' }).click();
  await expect(panel.locator('.ai-sources')).toContainText('第2版');
  await openSources(panel);
  await panel.locator('.ai-sources summary').filter({ hasText: '新人報到指南.txt' }).click();
  await expect(panel.locator('.ai-sources')).toContainText('五樓');
  await panel.getByLabel('詢問 AI').fill('設備申請流程');
  await panel.getByRole('button', { name: '送出 AI 問題' }).click();
  await expect(panel.locator('.ai-sources').last()).toContainText('附件・設備申請流程.txt');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(await panel.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath(`formal-${width}.png`), fullPage: true });
  await chooseCategory(panel, '新人報到');
  await expect(panel.locator('.copilot-message')).toHaveCount(0);
  await expect(panel).toContainText('23 份可見文件');
  expect(errors).toEqual([]);
});
