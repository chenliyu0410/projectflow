import { expect, test } from '@playwright/test';
import { openAccount, openActions, openProjects } from './navigation';

for (const width of [1280,375]) test(`account, floating assistant and action dropdown ${width}`, async ({page, request}, info) => {
  expect(await (await request.get('/api/health/acceptance')).json()).toEqual({acceptance:true});
  await page.setViewportSize({width,height:720});
  await page.goto('/');
  await page.getByLabel('帳號',{exact:true}).fill('yu');
  await page.getByLabel('密碼',{exact:true}).fill('demo-yu');
  await page.getByRole('button',{name:'登入',exact:true}).click();
  const user=page.getByRole('button',{name:'使用者選單',exact:true});
  await expect(user).toContainText('游專案');
  const box=await user.boundingBox();
  expect(box!.y).toBeLessThan(30); expect(box!.x + box!.width).toBeGreaterThan(width-40);
  await expect(page.locator('.workspace-navigation .sidebar-session')).toHaveCount(0);
  const account=await openAccount(page);
  await expect(account.getByRole('button',{name:'登出'})).toBeVisible();
  await expect(account.getByLabel('切換公司（本機展示）')).toBeVisible();
  await page.keyboard.press('Escape'); await expect(user).toBeFocused();
  const assistant=page.getByRole('complementary',{name:'AI 專案副手'});
  const launcher=page.getByRole('button',{name:'切換 AI 副手'});
  await expect(assistant).toBeHidden();
  const area=await page.locator('.workspace-main').boundingBox();
  expect(area!.width).toBe(width>860 ? width-252 : width);
  const icon=await launcher.boundingBox();
  expect(icon!.x + icon!.width).toBeGreaterThan(width-30); expect(icon!.y).toBeGreaterThan(620);
  await launcher.click(); await expect(assistant).toBeVisible();
  const assistantBox=await assistant.boundingBox();
  expect(assistantBox!.y).toBeGreaterThanOrEqual(40);
  expect(assistantBox!.y + assistantBox!.height).toBeLessThanOrEqual(640);
  if (width>860) expect(assistantBox!.width).toBe(520);
  await assistant.getByLabel('詢問 AI').fill('保留尚未送出的問題');
  await assistant.getByRole('button',{name:'關閉 AI 副手'}).click();
  await expect(launcher).toBeFocused();
  await launcher.click(); await expect(assistant.getByLabel('詢問 AI')).toHaveValue('保留尚未送出的問題');
  await page.screenshot({path:info.outputPath('floating-assistant.png')});
  await page.keyboard.press('Escape'); await expect(assistant).toBeHidden();
  await (await openProjects(page)).getByRole('button',{name:'成貓主食罐正式版',exact:true}).click();
  const phases=page.getByRole('region',{name:'開發階段與閘門'});
  await expect(phases.getByRole('button',{name:'進入階段：市場與配方'})).toContainText('進行中');
  await expect(phases.getByRole('button',{name:'進入階段：市場與配方'}).getByLabel('進行中階段')).toBeVisible();
  await expect(phases.getByRole('button',{name:'進入階段：小量試作'})).toContainText('尚未開始');
  await expect(phases.getByRole('button',{name:'進入階段：小量試作'})).toBeDisabled();
  await expect(phases.getByRole('button',{name:'進入階段：市場與配方'})).toBeEnabled();
  const trigger=page.getByRole('button',{name:'專案操作',exact:true});
  await expect(trigger).toContainText('新增子節點');
  await expect(page.getByRole('button',{name:'新增子節點',exact:true})).toBeHidden();
  for (const name of ['另存為模板','套用模板']) {
    const menu=await openActions(page);
    await expect(menu.getByRole('button')).toHaveCount(3);
    await expect(menu.getByRole('button').first()).toContainText('新增子節點');
    await menu.getByRole('button',{name,exact:true}).click();
    const dialog=page.getByRole('dialog',{name,exact:true});
    await expect(dialog).toBeVisible();
    await expect(trigger).toHaveAttribute('aria-expanded','false');
    await dialog.getByRole('button',{name:'取消',exact:true}).click();
    await expect(dialog).toBeHidden();
  }
  await (await openActions(page)).getByRole('button',{name:'新增子節點',exact:true}).click();
  const form=page.getByRole('form',{name:'新增節點表單'});
  await expect(form).toBeVisible();
  await form.getByRole('button',{name:'取消',exact:true}).click();
  await expect(form).toBeHidden();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  const visibleActions=await openActions(page);
  const menuBox=await visibleActions.boundingBox();
  expect(menuBox!.x).toBeGreaterThanOrEqual(0);
  expect(menuBox!.x + menuBox!.width).toBeLessThanOrEqual(width);
  await page.screenshot({path:info.outputPath('header-actions.png')});
  await page.keyboard.press('Escape');
  await (await openAccount(page)).getByRole('button',{name:'登出',exact:true}).click();
  await page.getByLabel('帳號',{exact:true}).fill('lin');
  await page.getByLabel('密碼',{exact:true}).fill('demo-lin');
  await page.getByRole('button',{name:'登入',exact:true}).click();
  await (await openProjects(page)).getByRole('button',{name:'成貓主食罐正式版',exact:true}).click();
  await expect(page.getByRole('heading',{name:'成貓主食罐正式版',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'專案操作',exact:true})).toHaveCount(0);
});
