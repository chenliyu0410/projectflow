async function login(page: Page, username = 'yu') {
  await page.goto('/');
  await page.getByLabel('帳號', { exact: true }).fill(username);
  await page.getByLabel('密碼', { exact: true }).fill('demo-' + username);
  await page.getByRole('button', { name: '登入', exact: true }).click();
  await expect(page.getByLabel('可見任務完成率', { exact: true })).toBeVisible();
}
async function arrange(page: Page) {
  const title = 'UX 隔離驗證 ' + randomUUID().slice(0, 8);
  const response = await page.request.post('/api/projects', { data: { title } });
  expect(response.status()).toBe(201);
  const id = (await response.json()).id;
  const root = (await (await page.request.get('/api/projects/' + id)).json()).nodes[0].id;
  const add = async (title: string, parent: string, kind = 'task') => {
    const response = await page.request.post('/api/projects/' + id + '/nodes', { data: { title, parent_id: parent, kind, start_date: '2026-10-01', due_date: '2026-10-20' } });
    expect(response.status()).toBe(201); return (await response.json()).id as string;
  };
  const phase = await add('工作階段', root, 'phase');
  const a = await add('新增目標', phase);
  const b = await add('保持收合', phase);
  await add('既有子任務', a);
  await add('隱藏子任務', b);
  const closed = await add('已完成階段', root, 'phase');
  expect((await page.request.patch('/api/nodes/' + closed + '/status', { data: { status: 'done' } })).status()).toBe(200);
  await page.reload();
  if (page.viewportSize()!.width < 720) await page.getByRole('button', { name: '切換導覽' }).click();
  await page.getByLabel('專案清單').getByRole('button', { name: title, exact: true }).click();
  await page.getByRole('tab', { name: '時程', exact: true }).click();
  return { id, title, a };
}
