def main():
    current=ROOT/'current'; history=ROOT/'history'
    current.mkdir(exist_ok=True); history.mkdir(exist_ok=True)
    manifest={'synthetic':True,'project_title':'【虛構展示】山嵐新品 RAG 知識驗證','created_at':'2026-10-21','documents':[]}
    for name,content in DOCS.items():
        body=(content if name.endswith('.csv') else NOTICE+content).encode('utf-8')
        (current/name).write_bytes(body)
        item={'key':name[:2],'filename':name,'path':'current/'+name,'version':2 if name.startswith('05') else 1,'sha256':hashlib.sha256(body).hexdigest()}
        if name.startswith('05'):
            old=NOTICE+OLD; hp=history/'05_包裝規格_v1.txt';hp.write_bytes(old.encode('utf-8'))
            item.update(history_path='history/'+hp.name,history_sha256=hashlib.sha256(hp.read_bytes()).hexdigest())
        manifest['documents'].append(item)
    questions=[{'id':i,'category':category,'question':q,'expected_answer':answer,'required_document_keys':[f'{k:02}' for k in docs], 'term_groups':terms,'expect_refusal':i in {'Q17','Q18','Q19','Q20'}} for i,category,q,answer,docs,terms in QUESTIONS]
    assert len(DOCS)==10 and len(questions)==20
    for name,data in [('manifest.json',manifest),('questions.json',questions)]:
        (ROOT/name).write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    key=['# 虛構 RAG 題庫與標準答案','',NOTICE.strip(),'','本檔與 questions.json 僅供驗收，**不要上傳到知識庫**，避免答案洩漏污染評測。','', '| 題號 | 類型 | 問題 | 標準答案 | 必要來源 |','|---|---|---|---|---|']
    key += [f"| {q['id']} | {q['category']} | {q['question']} | {q['expected_answer']} | {', '.join(q['required_document_keys']) or '應明示資料不足'} |" for q in questions]
    (ROOT/'標準問答.md').write_text('\n'.join(key)+'\n',encoding='utf-8')
    with zipfile.ZipFile(ROOT/'RAG虛構資料包.zip','w',zipfile.ZIP_DEFLATED) as z:
        for folder in (current,history):
            for p in sorted(folder.iterdir()):z.write(p,p.relative_to(ROOT))
        for name in ['manifest.json','questions.json','標準問答.md','README.md','evaluation.json','試跑結果.md']:
            if (ROOT/name).is_file():z.write(ROOT/name,name)
    print(json.dumps({'documents':10,'historical_versions':1,'questions':20,'synthetic':True}))

if __name__=='__main__':main()
